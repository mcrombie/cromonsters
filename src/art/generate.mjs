class Plate {
  constructor(width = 80, height = 72) {
    this.width = width;
    this.height = height;
    this.pixels = Array.from({ length: height }, () => Array(width).fill(-1));
  }
  dot(x, y, ink = 0) {
    x = Math.round(x);
    y = Math.round(y);
    if (x >= 0 && y >= 0 && x < this.width && y < this.height) this.pixels[y][x] = ink;
    return this;
  }
  rect(x, y, w, h, ink = 0) {
    for (let py = y; py < y + h; py++) for (let px = x; px < x + w; px++) this.dot(px, py, ink);
    return this;
  }
  line(points, ink = 0, width = 1) {
    for (let i = 1; i < points.length; i++) {
      let [x, y] = points[i - 1];
      const [tx, ty] = points[i];
      const dx = Math.abs(tx - x),
        dy = -Math.abs(ty - y),
        sx = x < tx ? 1 : -1,
        sy = y < ty ? 1 : -1;
      let error = dx + dy;
      while (true) {
        this.rect(x - Math.floor(width / 2), y - Math.floor(width / 2), width, width, ink);
        if (x === tx && y === ty) break;
        const twice = error * 2;
        if (twice >= dy) {
          error += dy;
          x += sx;
        }
        if (twice <= dx) {
          error += dx;
          y += sy;
        }
      }
    }
    return this;
  }
  poly(points, ink = 1, edge = 0) {
    const minY = Math.max(0, Math.min(...points.map((p) => p[1]))),
      maxY = Math.min(this.height - 1, Math.max(...points.map((p) => p[1])));
    for (let y = minY; y <= maxY; y++) {
      const crossings = [];
      for (let i = 0, j = points.length - 1; i < points.length; j = i++) {
        const [ax, ay] = points[i],
          [bx, by] = points[j];
        if (ay > y !== by > y) crossings.push(ax + ((y - ay) * (bx - ax)) / (by - ay));
      }
      crossings.sort((a, b) => a - b);
      for (let i = 0; i < crossings.length; i += 2)
        for (let x = Math.ceil(crossings[i]); x <= Math.floor(crossings[i + 1]); x++)
          this.dot(x, y, ink);
    }
    if (edge >= 0) this.line([...points, points[0]], edge);
    return this;
  }
  oval(cx, cy, rx, ry, ink = 1, edge = 0) {
    for (let y = cy - ry; y <= cy + ry; y++)
      for (let x = cx - rx; x <= cx + rx; x++) {
        if (((x - cx) / rx) ** 2 + ((y - cy) / ry) ** 2 <= 1) {
          const inside =
            ((x - cx) / Math.max(0.5, rx - 1)) ** 2 + ((y - cy) / Math.max(0.5, ry - 1)) ** 2 <= 1;
          this.dot(x, y, inside || edge < 0 ? ink : edge);
        }
      }
    return this;
  }
  /** Fixed, sparse engraving marks are clipped to the chosen existing ink. */
  grain(from = 1, to = 2, seed = 1, density = 11, region = [0, 0, 80, 72]) {
    const [l, t, r, b] = region;
    for (let y = t; y < b; y++)
      for (let x = l; x < r; x++) {
        let hash = Math.imul(x + seed * 131, 374761393) ^ Math.imul(y + seed * 17, 668265263);
        hash = Math.imul(hash ^ (hash >>> 13), 1274126177);
        if (this.pixels[y]?.[x] === from && ((hash ^ (hash >>> 16)) >>> 0) % density === 0)
          this.dot(x, y, to);
      }
    return this;
  }
  svg(title) {
    const runs = [];
    for (let y = 0; y < this.height; y++)
      for (let x = 0; x < this.width;) {
        const ink = this.pixels[y][x];
        let end = x + 1;
        while (end < this.width && this.pixels[y][end] === ink) end++;
        if (ink >= 0)
          runs.push(`<rect x="${x}" y="${y}" width="${end - x}" height="1" fill="${inks[ink]}"/>`);
        x = end;
      }
    return `<svg xmlns="http://www.w3.org/2000/svg" width="${this.width}" height="${this.height}" viewBox="0 0 ${this.width} ${this.height}" role="img" aria-label="${title}" shape-rendering="crispEdges"><title>${title}</title>${runs.join('')}</svg>\n`;
  }
}

